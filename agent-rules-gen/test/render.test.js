import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { parseRules, renderRules } from '../lib/index.js';

const source = `---
agents: [codex, claude]
claude: |
  ## Review
  Explain the patch before changing files.
---
## Review
Keep patches small.

---
agents: [codex]
---
## Commands
Run the unit tests.

---
agents: [claude]
---
## Notes
Summarize the result.
`;

test('filters sections and replaces wording for each agent', () => {
  const rendered = renderRules(source);
  assert.match(rendered['AGENTS.md'], /Keep patches small\./);
  assert.match(rendered['AGENTS.md'], /Run the unit tests\./);
  assert.doesNotMatch(rendered['AGENTS.md'], /Explain the patch|Summarize the result/);
  assert.match(rendered['CLAUDE.md'], /Explain the patch/);
  assert.match(rendered['CLAUDE.md'], /Summarize the result/);
  assert.doesNotMatch(rendered['CLAUDE.md'], /Keep patches small|Run the unit tests/);
  assert.deepEqual(renderRules(source), rendered);
  assert.equal(parseRules(source).length, 3);
});

test('hashes the complete LF-normalized source and identifies generated blocks', () => {
  const hash = createHash('sha256').update(source).digest('hex');
  const text = renderRules(source)['AGENTS.md'];
  assert.ok(text.includes(hash));
  assert.match(text, /Generated by agent-rules-gen/);
  assert.match(text, /Source: "rules.md"/);
  assert.match(text, /^<!-- agent-rules-gen:begin -->/);
  assert.match(text, /<!-- agent-rules-gen:end -->$/);
  assert.equal(renderRules(source.replace(/\n/g, '\r\n'))['AGENTS.md'], text);
  assert.equal(renderRules('\uFEFF' + source)['AGENTS.md'], text);
  assert.notEqual(renderRules(source + '\n')['AGENTS.md'], text);
});

test('keeps fenced code, horizontal rules in fences and markdown whitespace', () => {
  const body = '## Example\n\n```yaml\n---\nagents: [nobody]\n---\n```\n\n~~~~md\n---\n~~~\n~~~~\nLine with break  \nNext';
  const rendered = renderRules(`---\nagents: [codex]\n---\n${body}\n`);
  assert.ok(rendered['AGENTS.md'].includes(body));
  assert.doesNotMatch(rendered['CLAUDE.md'], /Example|Line with break/);
});

test('allows override-only sections and escapes source names in comments', () => {
  const rendered = renderRules('---\nagents: [claude]\nclaude: |\n  Only wording.\n---\n', {
    sourceName: 'rules-->draft.md',
  });
  assert.match(rendered['CLAUDE.md'], /Only wording\./);
  assert.doesNotMatch(rendered['CLAUDE.md'], /rules-->draft/);
});

for (const [name, invalid] of [
  ['empty source', ''],
  ['unmarked prose', '# Rules\n'],
  ['unknown agent', '---\nagents: [cluade]\n---\nText'],
  ['duplicate agent', '---\nagents: [codex, codex]\n---\nText'],
  ['unknown key', '---\nagents: [codex]\nextra: yes\n---\nText'],
  ['duplicate key', '---\nagents: [codex]\nagents: [claude]\n---\nText'],
  ['missing agents', '---\nclaude: |\n  Text\n---\nText'],
  ['empty agents', '---\nagents: []\n---\nText'],
  ['unselected override', '---\nagents: [codex]\nclaude: |\n  Text\n---\nText'],
  ['unsupported scalar', '---\nagents: [codex]\ncodex: Text\n---\nText'],
  ['empty body', '---\nagents: [codex]\n---\n'],
  ['empty override', '---\nagents: [codex]\ncodex: |\n---\nText'],
  ['unterminated header', '---\nagents: [codex]\n'],
  ['unterminated fence', '---\nagents: [codex]\n---\n```\ntext'],
  ['unterminated fence in an override', '---\nagents: [codex]\ncodex: |\n  ```\n  text\n---\nText'],
  ['reserved marker', '---\nagents: [codex]\n---\n<!-- agent-rules-gen:begin -->'],
  ['lone carriage return', '---\nagents: [codex]\n---\nText\rOther'],
]) {
  test(`rejects ${name}`, () => assert.throws(() => parseRules(invalid), /line|source/i));
}
