import { createHash, randomUUID } from 'node:crypto';
import {
  chmodSync, closeSync, fsyncSync, lstatSync, mkdirSync, openSync, readFileSync,
  realpathSync, renameSync, unlinkSync, writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';

const TARGETS = { codex: 'AGENTS.md', claude: 'CLAUDE.md' };
const BEGIN = '<!-- agent-rules-gen:begin -->';
const END = '<!-- agent-rules-gen:end -->';

function normalized(source) {
  if (typeof source !== 'string') throw new TypeError('Rules source must be a string');
  const text = source.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
  if (text.includes('\r')) throw new Error('Rules source contains a lone carriage return');
  if (text.includes('<!-- agent-rules-gen')) throw new Error('Rules source contains a reserved marker');
  return text;
}

/**
 * Advance a Markdown code-fence state by one line. `fence` is the opening run
 * (a run of backticks or tildes) while inside a fence, otherwise undefined.
 */
function advanceFence(line, fence) {
  const marker = /^ {0,3}(`{3,}|~{3,})(.*)$/.exec(line);
  if (!marker) return fence;
  const [, run, rest] = marker;
  if (fence) {
    return run[0] === fence[0] && run.length >= fence.length && !rest.trim() ? undefined : fence;
  }
  return run[0] === '~' || !rest.includes('`') ? run : undefined;
}

function trimmedLines(lines) {
  const copy = [...lines];
  while (copy.length && /^\s*$/.test(copy[0])) copy.shift();
  while (copy.length && /^\s*$/.test(copy.at(-1))) copy.pop();
  return copy.join('\n');
}

/** Parse the documented metadata subset. Markdown bodies stay literal. */
export function parseRules(source) {
  const lines = normalized(source).split('\n');
  const sections = [];
  let cursor = 0;
  const fail = (message) => { throw new Error(`Rules source line ${cursor + 1}: ${message}`); };

  while (cursor < lines.length) {
    if (!lines[cursor].trim()) { cursor++; continue; }
    if (lines[cursor] !== '---') fail('expected a section header (---)');
    cursor++;
    const metadata = new Map();
    while (cursor < lines.length && lines[cursor] !== '---') {
      if (!lines[cursor].trim()) { cursor++; continue; }
      const entry = /^(agents|codex|claude):\s*(.*?)\s*$/.exec(lines[cursor]);
      if (!entry) fail('unknown or malformed metadata');
      const [, key, value] = entry;
      if (metadata.has(key)) fail(`duplicate ${key}`);
      cursor++;
      if (key === 'agents') {
        const list = /^\[\s*(codex|claude)(\s*,\s*(codex|claude))*\s*\]$/.exec(value);
        if (!list) fail('agents must be [codex], [claude] or [codex, claude]');
        const agents = value.slice(1, -1).split(',').map((agent) => agent.trim());
        if (new Set(agents).size !== agents.length) fail('duplicate agent');
        metadata.set(key, agents);
      } else {
        if (value !== '|') fail('wording overrides must use a literal block (|)');
        const wording = [];
        while (cursor < lines.length && (lines[cursor].startsWith('  ') || !lines[cursor].trim())) {
          wording.push(lines[cursor].slice(2));
          cursor++;
        }
        const text = trimmedLines(wording);
        if (!text) fail('empty wording override');
        if (wording.reduce((open, line) => advanceFence(line, open), undefined)) {
          fail('unterminated code fence in wording override');
        }
        metadata.set(key, text);
      }
    }
    if (cursor === lines.length) fail('unterminated section header');
    cursor++;
    const agents = metadata.get('agents');
    if (!agents) fail('missing agents');
    const wording = {};
    for (const [key, value] of metadata) {
      if (key === 'agents') continue;
      if (!agents.includes(key)) fail(`override for unselected agent ${key}`);
      wording[key] = value;
    }

    const bodyLines = [];
    let fence;
    while (cursor < lines.length) {
      const line = lines[cursor];
      if (!fence && line === '---') break;
      fence = advanceFence(line, fence);
      bodyLines.push(line);
      cursor++;
    }
    if (fence) fail('unterminated code fence');
    const body = trimmedLines(bodyLines);
    if (agents.some((agent) => !(wording[agent] ?? body))) fail('empty section body');
    sections.push({ agents, wording, body });
  }
  if (!sections.length) fail('at least one section is required');
  return sections;
}

function render(sections, hash, sourceName, agent, eol) {
  const name = JSON.stringify(sourceName).replace(/</g, '\\u003c').replace(/>/g, '\\u003e');
  const body = sections.filter((section) => section.agents.includes(agent))
    .map((section) => section.wording[agent] ?? section.body).join('\n\n');
  return [
    BEGIN,
    '<!-- Generated by agent-rules-gen. Do not edit this block.',
    `Source: ${name}`,
    `Source SHA-256 (UTF-8, LF, no BOM): ${hash}`,
    `Target: ${agent}`,
    '-->',
    '',
    body,
    '',
    END,
  ].join('\n').replace(/\n/g, eol);
}

/** Return complete generated blocks (without a final newline), keyed by filename. */
export function renderRules(source, { sourceName = 'rules.md', eol = '\n' } = {}) {
  if (eol !== '\n' && eol !== '\r\n') throw new Error('eol must be LF or CRLF');
  if (typeof sourceName !== 'string') throw new TypeError('sourceName must be a string');
  const sections = parseRules(source);
  const hash = createHash('sha256').update(normalized(source), 'utf8').digest('hex');
  return Object.fromEntries(Object.entries(TARGETS).map(([agent, file]) =>
    [file, render(sections, hash, sourceName, agent, eol)]));
}

function readText(file) {
  const bytes = readFileSync(file);
  try {
    // Preserve the BOM as part of unmanaged text, and reject lossy decoding.
    return new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(bytes);
  } catch {
    throw new Error(`${file}: expected valid UTF-8`);
  }
}

function newline(text, fallback = '\n') {
  return /\r?\n/.exec(text)?.[0] ?? fallback;
}

function locateBlock(text) {
  const markers = [];
  let offset = text.startsWith('\uFEFF') ? 1 : 0;
  let fence;
  for (const line of text.slice(offset).split('\n')) {
    const content = line.replace(/\r$/, '');
    // Marker text quoted inside a fenced code block is documentation, not a marker.
    if (!fence && content.includes('<!-- agent-rules-gen')) {
      if (content !== BEGIN && content !== END) throw new Error('malformed generated block marker');
      markers.push({ marker: content, start: offset, end: offset + content.length });
    }
    fence = advanceFence(content, fence);
    offset += line.length + 1;
  }
  if (fence) throw new Error('unterminated code fence in the destination file');
  if (!markers.length) return null;
  if (markers.length !== 2 || markers[0].marker !== BEGIN || markers[1].marker !== END) {
    throw new Error('expected exactly one ordered begin/end marker pair');
  }
  return { start: markers[0].start, end: markers[1].end };
}

function prepare({ source = 'rules.md', outDir = '.', cwd = process.cwd() } = {}) {
  const sourcePath = resolve(cwd, source);
  const outputPath = resolve(cwd, outDir);
  const sourceText = readText(sourcePath);
  const sourceName = relative(outputPath, sourcePath).split(sep).join('/');
  const blocks = renderRules(sourceText, { sourceName });
  const sourceRealPath = realpathSync(sourcePath);
  return Object.entries(blocks).map(([name, block]) => {
    const file = join(outputPath, name);
    try {
      let stat;
      try { stat = lstatSync(file); } catch (error) {
        if (error.code !== 'ENOENT') throw error;
      }
      if (stat?.isSymbolicLink()) throw new Error('refusing a symbolic link destination');
      if (stat && !stat.isFile()) throw new Error('destination must be a regular file');
      if (stat && realpathSync(file) === sourceRealPath) throw new Error('source and destination are the same file');
      const current = stat ? readText(file) : '';
      const region = locateBlock(current);
      const eol = newline(region ? current.slice(region.start, region.end) : current, newline(sourceText));
      const expected = block.replace(/\n/g, eol);
      let next;
      let reason;
      if (region) {
        next = current.slice(0, region.start) + expected + current.slice(region.end);
        if (current !== next) reason = 'generated block is stale or edited';
      } else {
        const hasText = current.replace(/^\uFEFF/, '').length > 0;
        const separator = hasText ? (current.endsWith('\n') ? eol : eol + eol) : '';
        next = current + separator + expected + eol;
        reason = stat ? 'generated block is missing' : 'file is missing';
      }
      return { file, current, next, mode: stat?.mode, reason };
    } catch (error) {
      return { file, error, reason: error.message };
    }
  });
}

/** Read-only freshness check; malformed source throws, output problems are issues. */
export function check(options) {
  const issues = prepare(options).filter((entry) => entry.reason)
    .map(({ file, reason }) => ({ file, reason }));
  return { ok: issues.length === 0, issues };
}

function replaceFile(file, content, mode) {
  const temporary = join(dirname(file), `.agent-rules-gen-${randomUUID()}.tmp`);
  const descriptor = openSync(temporary, 'wx', mode === undefined ? 0o666 : mode & 0o777);
  try {
    try {
      writeFileSync(descriptor, content, 'utf8');
      fsyncSync(descriptor);
    } finally {
      closeSync(descriptor);
    }
    if (mode !== undefined && process.platform !== 'win32') chmodSync(temporary, mode & 0o777);
    renameSync(temporary, file);
  } finally {
    try { unlinkSync(temporary); } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
}

/** Update generated blocks only. Validate both destinations before any write. */
export function generate(options) {
  const entries = prepare(options);
  const invalid = entries.find((entry) => entry.error);
  if (invalid) throw new Error(`${invalid.file}: ${invalid.reason}`, { cause: invalid.error });
  const changed = [];
  for (const { file, current, next, mode } of entries) {
    if (current === next) continue;
    mkdirSync(dirname(file), { recursive: true });
    replaceFile(file, next, mode);
    changed.push(file);
  }
  return { ok: true, changed };
}
